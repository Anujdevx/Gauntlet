"""Alembic environment.

Runs migrations with the same async engine the application uses, and takes the
URL from ``POSTGRES_DSN`` rather than ``alembic.ini``. One source of truth for the
database location: a URL in the ini file is a URL that eventually disagrees with
the environment and applies migrations to the wrong database.

Also installs the DAG acyclicity guard. The specification requires the
``concept_edges`` graph to be acyclic, and the right place to enforce that is the
database, not the application -- the DAG is written by the syllabus decomposer,
the template seeder, and admins, and a check only one of them performs is not a
check.
"""

from __future__ import annotations

import asyncio
import sys
from logging.config import fileConfig
from pathlib import Path

from alembic import context
from sqlalchemy import Connection, pool
from sqlalchemy.ext.asyncio import async_engine_from_config


def _bootstrap_sys_path() -> None:
    """Put the workspace source roots on ``sys.path``, independent of the CWD.

    Alembic's ``prepend_sys_path`` is resolved against the *current working
    directory*, so ``alembic -c apps/api/alembic.ini`` from the repository root and
    the same command from ``apps/api`` would import different things -- and the
    second would fail outright, because this is a uv workspace where the packages
    live under ``*/src`` and are not installed into the interpreter that runs the
    migration.

    Deriving the paths from ``__file__`` makes the migration behave identically no
    matter where it is invoked from, which is the only property that matters for a
    command that runs in CI, in a container, and on a developer's machine.
    """
    here = Path(__file__).resolve()
    repo_root = here.parents[3]
    for relative in ("apps/api/src", "apps/worker/src", "engine/src"):
        candidate = str(repo_root / relative)
        if candidate not in sys.path:
            sys.path.insert(0, candidate)


_bootstrap_sys_path()

# Imported after the path bootstrap, deliberately: importing at module scope above
# would fail on a fresh checkout with no install.
from oa_api.models.tables import Base  # noqa: E402

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = Base.metadata


def get_url() -> str:
    """Resolve the database URL from the environment.

    ``config.set_main_option`` percent-escapes, so a DSN containing ``%`` would be
    mangled; assigning to ``config.attributes`` avoids that entirely.
    """
    from oa_engine.platform.config import get_settings

    return get_settings().postgres_dsn


def run_migrations_offline() -> None:
    """Emit SQL to stdout without connecting. Used to review a migration."""
    context.configure(
        url=get_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        compare_type=True,
        compare_server_default=True,
    )
    with context.begin_transaction():
        context.run_migrations()


def do_run_migrations(connection: Connection) -> None:
    """Apply migrations on an established connection."""
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        # Type and server-default comparison are on because the whole value of a
        # migration review is catching an unintended change; a drift here is
        # exactly what a reviewer would want to see autogenerated.
        compare_type=True,
        compare_server_default=True,
    )
    with context.begin_transaction():
        context.run_migrations()


async def run_async_migrations() -> None:
    """Create an async engine and run the migrations through it."""
    engine = async_engine_from_config(
        {"sqlalchemy.url": get_url()},
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    async with engine.connect() as connection:
        await connection.run_sync(do_run_migrations)
    await engine.dispose()


def run_migrations_online() -> None:
    """Entry point for online migrations."""
    asyncio.run(run_async_migrations())


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
